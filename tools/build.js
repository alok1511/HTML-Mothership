#!/usr/bin/env node
/*
 * Optional build step (needs Node.js, NOT needed to use Mothership).
 *   node tools/build.js
 * 1. samples/src/*.html  ->  samples/*.html (libraries inlined, fully offline)
 *                        ->  samples/samples.js (so the "Try a sample" button works from file://)
 * 2. dist/mothership-standalone.html: Mothership + all its libraries in ONE file
 *    (handy for emailing / putting on a shared drive).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const esc = s => s.replace(/<\/script/gi, '<\\/script');

// The package, editor and both MCP entry points publish the same release number.
const version = JSON.parse(read('package.json')).version;
for (const p of ['src/js/app.js', 'tools/mcp/mothership-mcp.js', 'tools/mcp/mothership_mcp.py']) {
  if ((/VERSION = '([^']+)'/.exec(read(p)) || [])[1] !== version) throw new Error('Version mismatch: ' + p + ' (expected ' + version + ')');
}

// 1. samples
const srcDir = path.join(root, 'samples/src');
const bundle = {};
const ids = { 'sales-dashboard.html': 'sales', 'ops-dashboard.html': 'ops', 'risk-dashboard.html': 'risk' };
for (const f of fs.readdirSync(srcDir).filter(f => f.endsWith('.html'))) {
  let html = fs.readFileSync(path.join(srcDir, f), 'utf8');
  html = html.replace(/<script data-inline="([^"]+)"><\/script>/g, (m, p) => '<script>/* ' + p.split('/').pop() + ' (inlined) */\n' + esc(read(p)) + '\n</script>');
  fs.writeFileSync(path.join(root, 'samples', f), html);
  bundle[ids[f] || f.replace(/\.html$/, '')] = { name: f, html };
  console.log('sample  ', f, (html.length / 1024).toFixed(0) + ' KB');
}
fs.writeFileSync(path.join(root, 'samples/samples.js'), '/* generated by tools/build.js */\nwindow.MS_SAMPLES = ' + JSON.stringify(bundle).replace(/</g, '\\u003c') + ';\n');
console.log('bundle   samples/samples.js');

// 2. library sources that Mothership puts inside dashboards (loadable from file://)
fs.writeFileSync(path.join(root, 'vendor/charts/chart.src.js'), '/* generated by tools/build.js from chart.umd.min.js */\n(window.MS_LIBSRC = window.MS_LIBSRC || {}).chartjs = ' + JSON.stringify(read('vendor/charts/chart.umd.min.js')).replace(/</g, '\\u003c') + ';\n');
console.log('libsrc   vendor/charts/chart.src.js');

// 3. Keep the in-app guide and lesson handout in sync with the authored sources.
const markdown = read('docs/USER-GUIDE.md'), marked = require('../vendor/marked.min.js');
const sections = markdown.split(/<!-- guide:([a-z-]+) -->\s*/).slice(1);
const guide = [];
for (let i = 0; i < sections.length; i += 2) {
  const [, title, content] = /^## (.+)\r?\n([\s\S]*)$/.exec(sections[i + 1].trim()) || [];
  if (!title) throw new Error('Guide chapter needs a heading: ' + sections[i]);
  guide.push({ id: sections[i], title, html: marked.parse(content, { gfm: true }) });
}
const lessons = JSON.parse(read('docs/lessons.json'));
const practice = Object.fromEntries(fs.readdirSync(path.join(root, 'docs/practice')).filter(f => f.endsWith('.csv')).sort().map(f => [f, read('docs/practice/' + f)]));
const learn = '/* generated by tools/build.js from docs/USER-GUIDE.md and docs/lessons.json */\nwindow.MS_LEARN = ' +
  JSON.stringify({ guide, lessons, markdown, practice }).replace(/</g, '\\u003c') + ';\n';
fs.writeFileSync(path.join(root, 'src/js/learn-content.js'), learn);
fs.writeFileSync(path.join(root, 'docs/TUTORIAL.md'), [
  '# Mothership practice lessons', '',
  'Open Help › Tutorial in the editor, or follow the steps below. Start in the separate sales practice copy; you do not need your own dashboard.',
  '', 'For more detail see [the user guide](USER-GUIDE.md). Some steps can be checked automatically; others ask you to confirm what you saw.',
  ...lessons.flatMap((l, i) => ['', '## ' + (i + 1) + '. ' + l.title + ' (' + l.minutes + ' min)', '', l.goal, '',
    ...l.steps.flatMap((st, j) => [(j + 1) + '. ' + st.do, '   **Check:** ' + st.see])]),
  '', 'The monthly refresh lesson’s CSV downloads are available inside the tutorial. For offline practice without the editor tutorial, use [October](practice/sales-practice-2026-10.csv) and [November](practice/sales-practice-2026-11.csv).', ''
].join('\n'));
console.log('help     ' + guide.length + ' guide chapters, ' + lessons.length + ' practice lessons');

// 4. single-file Mothership
let shell = read('mothership.html');
shell = shell.replace('<link rel="stylesheet" href="src/css/mothership.css">', () => '<style>\n' + read('src/css/mothership.css') + '\n</style>');
shell = shell.replace(/<script src="(src\/js\/[^"]+)"><\/script>/g, (m, p) => '<script>/* ' + p + ' */\n' + esc(read(p)) + '\n</script>');
const libs = { chartjs: 'vendor/charts/chart.umd.min.js', marked: 'vendor/marked.min.js', mammoth: 'vendor/mammoth.browser.min.js', xlsx: 'vendor/xlsx.full.min.js', jszip: 'vendor/jszip.min.js', pdf: 'vendor/pdf.min.js', pdfworker: 'vendor/pdf.worker.min.js' };
const libTags = Object.entries(libs).map(([k, p]) => '<script type="text/ms-lib" data-lib="' + k + '">' + esc(read(p)) + '</script>').join('\n');
const end = shell.lastIndexOf('</body>'); // the last one: scripts may contain '</body>' in strings
shell = shell.slice(0, end) + libTags + '\n<script>/* samples */\n' + esc(read('samples/samples.js')) + '\n</script>\n' + shell.slice(end);
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist/mothership-standalone.html'), shell);
console.log('single   dist/mothership-standalone.html', (shell.length / 1048576).toFixed(1) + ' MB');
